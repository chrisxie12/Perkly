const segmenter = typeof Intl !== "undefined" && "Segmenter" in Intl ? new Intl.Segmenter(undefined, { granularity: "grapheme" }) : null;

/** Same rule as private.is_emoji in the database: short, no ASCII, no letters. */
export function isEmoji(s: string | null | undefined) {
  if (!s) return false;
  const points = [...s].length;
  return points >= 1 && points <= 16 && !/[\x01-\x7F]/.test(s) && !/\p{L}/u.test(s);
}

/** A message that is only 1–3 emoji is shown large, without a bubble, like a sticker. */
export function isBigEmoji(body: string) {
  const text = body.trim();
  if (!text || /[\x01-\x7F]/.test(text.replace(/\s/g, "")) || /\p{L}|\p{N}/u.test(text)) return false;
  const graphemes = segmenter ? [...segmenter.segment(text.replace(/\s/g, ""))].length : [...text].length;
  return graphemes >= 1 && graphemes <= 3 && /\p{Extended_Pictographic}/u.test(text);
}
